"""Native skill generation stays deterministic, credential-free, and current."""

import json
from pathlib import Path
import tempfile
import tomllib
import unittest

from native import ROOT, invoke, response_server


class SkillTests(unittest.TestCase):
    def assert_success(self, result):
        self.assertEqual(result.returncode, 0, result.stderr)
        return result

    def test_committed_export_matches_running_cli(self):
        self.assert_success(invoke("skill", "--output", ROOT / "skills/decision", "--check"))
        references = ROOT / "skills/decision/references"
        for name in ("request.json", "images.json"):
            self.assertEqual(json.loads((references / name).read_text(encoding="utf-8")),
                             json.loads((ROOT / "examples" / name).read_text(encoding="utf-8")))
        version = tomllib.loads((ROOT / "Cargo.toml").read_text(encoding="utf-8"))["package"]["version"]
        self.assertEqual(self.assert_success(invoke("--version")).stdout.strip(), "decision " + version)
        self.assertIn("Generated by decision " + version,
                      (ROOT / "skills/decision/SKILL.md").read_text(encoding="utf-8"))

    def test_generation_ignores_provider_settings_and_credentials(self):
        with tempfile.TemporaryDirectory() as directory, response_server({}) as (url, requests):
            root = Path(directory)
            expected = self.assert_success(invoke("skill")).stdout
            settings = {"DECISION_PROVIDER": "invalid-provider", "DECISION_BASE_URL": "invalid-url",
                        "DECISION_MODEL": "private-model", "DECISION_API_KEY_ENV": "PRIVATE_VAR",
                        "PRIVATE_VAR": "do-not-export-credential", "COLUMNS": "25", "FORCE_COLOR": "1"}
            self.assertEqual(self.assert_success(invoke("skill", env=settings)).stdout, expected)
            outputs = []
            for name, env in (("normal", {}), ("ambient", settings)):
                output = root / name
                self.assert_success(invoke("skill", "--output", output, env=env))
                outputs.append({p.relative_to(output): p.read_bytes() for p in output.rglob("*") if p.is_file()})
            self.assertEqual(outputs[0], outputs[1])
            self.assertEqual(outputs[0][Path("SKILL.md")].decode(), expected)
            self.assert_success(invoke("skill", env={"DECISION_BASE_URL": url, "DECISION_API_KEY": "fixture-key"}))
            self.assertEqual(requests, [])
            for content in outputs[1].values():
                for value in ("do-not-export-credential", "invalid-url", "invalid-provider", "private-model"):
                    self.assertNotIn(value.encode(), content)

    def test_export_check_and_stale_detection(self):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            self.assert_success(invoke("skill", "--output", root))
            self.assert_success(invoke("skill", "--output", root, "--check"))
            self.assertEqual(json.loads((root / "references/request-schema.json").read_text(encoding="utf-8")),
                             json.loads((ROOT / "request.schema.json").read_text(encoding="utf-8")))
            (root / "SKILL.md").write_text("stale\n", encoding="utf-8")
            stale = invoke("skill", "--output", root, "--check")
            self.assertEqual(stale.returncode, 2, stale.stderr)
            self.assertEqual((root / "SKILL.md").read_text(encoding="utf-8"), "stale\n")
            self.assertEqual(invoke("skill", "--check").returncode, 2)


if __name__ == "__main__":
    unittest.main()
